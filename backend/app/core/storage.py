"""Where uploaded files are kept, behind a small interface (decision 0018).

The application only asks to save and read bytes under a key it generated itself. A hosted
object store can replace the local directory by implementing the same two methods.
"""

from pathlib import Path
from typing import Protocol


class FileNotStoredError(Exception):
    pass


class FileStore(Protocol):
    def save(self, key: str, data: bytes) -> None: ...

    def read(self, key: str) -> bytes: ...


class LocalFileStore:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    def _path_for(self, key: str) -> Path:
        path = (self._root / key).resolve()
        # Keys are generated by the application, never typed by a person. This guards against
        # a future mistake turning one into a way to reach files outside the upload directory.
        if not path.is_relative_to(self._root):
            raise FileNotStoredError("Invalid storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path_for(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, key: str) -> bytes:
        try:
            return self._path_for(key).read_bytes()
        except FileNotFoundError as error:
            raise FileNotStoredError("The file is missing from storage") from error
